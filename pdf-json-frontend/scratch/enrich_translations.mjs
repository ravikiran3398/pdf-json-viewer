// Now read translations.ts and dynamically import / merge
async function run() {
  const tsPath = path.resolve('src/i18n/translations.ts');
  const content = fs.readFileSync(tsPath, 'utf8');

  // Let's use tsx or regex/ast to insert into each language block
  // Let's do it cleanly by checking each language
  let updatedContent = content;

  for (const lang of ['en', 'es', 'fr', 'de', 'hi']) {
    const keys = newTranslations[lang];
    const linesToAdd = [];
    for (const [k, v] of Object.entries(keys)) {
      // Escape single quotes in value if any
      const safeVal = v.replace(/'/g, "\\'");
      linesToAdd.push(`    '${k}': '${safeVal}',`);
    }

    // Find the language block
    // Each block starts with `  ${lang}: {`
    const blockStart = `  ${lang}: {`;
    const idx = updatedContent.indexOf(blockStart);
    if (idx !== -1) {
      // Insert right after `  ${lang}: {`
      const insertPos = idx + blockStart.length;
      updatedContent = updatedContent.slice(0, insertPos) + '\n' + linesToAdd.join('\n') + updatedContent.slice(insertPos);
    }
  }

  fs.writeFileSync(tsPath, updatedContent, 'utf8');
  console.log('Successfully enriched translations.ts!');
}

run();
